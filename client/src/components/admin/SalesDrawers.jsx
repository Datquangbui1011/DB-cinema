import { useEffect, useState } from 'react';
import { Clock, Film, Ticket, User, XCircle } from 'lucide-react';
import { useAppContext } from '../../context/AppContext';
import { Badge, Drawer, EmptyState, Skeleton } from './ui';
import { formatDateTime, formatMoney, formatNumber, posterUrl } from '../../lib/adminFormat';
import { getTheaterType } from '../../lib/theaterTypes';

// Loads `url` when it changes; returns { data, error }
const useAdminFetch = (url) => {
    const { axios, getToken } = useAppContext();
    const [state, setState] = useState({ data: null, error: null });
    useEffect(() => {
        let cancelled = false;
        setState({ data: null, error: null });
        (async () => {
            try {
                const { data } = await axios.get(url, { headers: { Authorization: `Bearer ${await getToken()}` } });
                if (!cancelled) setState(data.success ? { data, error: null } : { data: null, error: data.message });
            } catch {
                if (!cancelled) setState({ data: null, error: 'Could not load details' });
            }
        })();
        return () => { cancelled = true; };
    }, [axios, getToken, url]);
    return state;
};

export const PaymentBadge = ({ isPaid, isSimulated }) => (
    <span className="inline-flex items-center gap-1.5">
        <Badge tone={isPaid ? 'success' : 'warning'}>{isPaid ? 'Paid' : 'Unpaid'}</Badge>
        {isSimulated && <span className="text-[10px] text-zinc-500" title="Generated by the traffic simulator">sim</span>}
    </span>
);

export const Avatar = ({ src, className = 'h-7 w-7' }) => src
    ? <img src={src} alt="" className={`${className} flex-shrink-0 rounded-full bg-zinc-800`} />
    : <div className={`${className} flex-shrink-0 rounded-full bg-zinc-800`} />;

const Row = ({ label, children }) => (
    <div className="flex items-start justify-between gap-4 py-2 text-sm">
        <span className="text-zinc-500">{label}</span>
        <span className="text-right text-zinc-100">{children}</span>
    </div>
);

/** One booking: customer, show, seats and payment */
export const BookingDrawer = ({ bookingId, onClose, onOpenCustomer, onOpenShow }) => {
    const { data, error } = useAdminFetch(`/api/admin/bookings/${bookingId}`);
    const b = data?.booking;
    const room = b?.theaterType ? getTheaterType(b.theaterType) : null;

    return (
        <Drawer title="Booking" subtitle={b ? `#${b.id}` : ''} onClose={onClose}>
            {error ? <EmptyState icon={XCircle} title={error} /> : !b ? <Skeleton className="h-96 w-full" /> : (
                <div className="space-y-5">
                    <div className="flex items-center justify-between">
                        <PaymentBadge isPaid={b.isPaid} isSimulated={b.isSimulated} />
                        <span className="text-lg font-semibold tabular-nums text-zinc-50">{formatMoney(b.amount)}</span>
                    </div>

                    <button onClick={() => onOpenCustomer(b.customerId)} className="flex w-full items-center gap-3 rounded-lg border border-zinc-800 p-3 text-left hover:bg-zinc-900">
                        <Avatar src={b.customerImage} className="h-9 w-9" />
                        <div className="min-w-0">
                            <p className="truncate text-sm font-medium text-zinc-100">{b.customer}</p>
                            <p className="truncate text-xs text-zinc-500">{b.customerEmail || 'No email'}</p>
                        </div>
                        <User className="ml-auto w-4 h-4 text-zinc-500" />
                    </button>

                    <button onClick={() => b.showId && onOpenShow(b.showId)} className="flex w-full gap-3 rounded-lg border border-zinc-800 p-3 text-left hover:bg-zinc-900">
                        <span className="h-20 w-14 flex-shrink-0 overflow-hidden rounded bg-zinc-800">
                            {posterUrl(b.poster_path) && <img src={posterUrl(b.poster_path, 'w92')} alt="" className="h-full w-full object-cover" />}
                        </span>
                        <div className="min-w-0">
                            <p className="truncate text-sm font-medium text-zinc-100">{b.movie}</p>
                            <p className="mt-1 flex items-center gap-1.5 text-xs text-zinc-400"><Clock className="w-3 h-3" />{b.showStart ? formatDateTime(b.showStart) : 'Show removed'}</p>
                            <div className="mt-1.5 flex flex-wrap gap-1.5">
                                {b.screenName && <Badge>{b.screenName}</Badge>}
                                {room && <Badge className={room.badge}>{room.name}</Badge>}
                            </div>
                        </div>
                        <Film className="ml-auto w-4 h-4 flex-shrink-0 text-zinc-500" />
                    </button>

                    <div>
                        <p className="mb-2 text-xs font-medium uppercase tracking-wider text-zinc-500">Seats ({b.seats.length})</p>
                        <div className="flex flex-wrap gap-1.5">
                            {b.seats.map(seat => <span key={seat} className="rounded-md bg-zinc-800 px-2 py-1 text-xs font-medium tabular-nums text-zinc-100">{seat}</span>)}
                        </div>
                    </div>

                    <div className="divide-y divide-zinc-800/80 border-t border-zinc-800/80">
                        <Row label="Booked">{formatDateTime(b.createdAt)}</Row>
                        <Row label="Price per ticket">{formatMoney(b.amount / Math.max(1, b.seats.length))}</Row>
                        <Row label="Payment reference">
                            {b.paymentReference ? <span className="font-mono text-xs">…{b.paymentReference.slice(-10)}</span> : <span className="text-zinc-500">None</span>}
                        </Row>
                        <Row label="Source">{b.isSimulated ? 'Traffic simulator' : 'Customer'}</Row>
                    </div>
                </div>
            )}
        </Drawer>
    );
};

/** One customer: totals, favourites and their recent bookings */
export const CustomerDrawer = ({ customerId, onClose, onOpenBooking }) => {
    const { data, error } = useAdminFetch(`/api/admin/customers/${encodeURIComponent(customerId)}`);
    const c = data?.customer;
    const stats = data?.stats;

    return (
        <Drawer title="Customer" subtitle={c?.email || ''} onClose={onClose} width="max-w-lg">
            {error ? <EmptyState icon={XCircle} title={error} /> : !c ? <Skeleton className="h-96 w-full" /> : (
                <div className="space-y-5">
                    <div className="flex items-center gap-3">
                        <Avatar src={c.image} className="h-12 w-12" />
                        <div className="min-w-0">
                            <p className="truncate text-base font-semibold text-zinc-50">{c.name}</p>
                            <p className="truncate text-xs text-zinc-500">{c.email}</p>
                        </div>
                        {c.isSimulated && <Badge tone="warning" className="ml-auto bg-amber-500/10 text-amber-400 border-amber-500/20">Simulated</Badge>}
                    </div>

                    <div className="grid grid-cols-3 gap-2">
                        {[
                            ['Total spent', formatMoney(stats.spent)],
                            ['Bookings', formatNumber(stats.bookings)],
                            ['Tickets', formatNumber(stats.tickets)],
                        ].map(([label, value]) => (
                            <div key={label} className="rounded-lg bg-zinc-900 px-3 py-2.5">
                                <p className="text-[11px] text-zinc-500">{label}</p>
                                <p className="mt-0.5 text-base font-semibold tabular-nums text-zinc-100">{value}</p>
                            </div>
                        ))}
                    </div>

                    <div className="divide-y divide-zinc-800/80 border-y border-zinc-800/80">
                        <Row label="First visit">{stats.firstVisit ? formatDateTime(stats.firstVisit) : '—'}</Row>
                        <Row label="Last visit">{stats.lastVisit ? formatDateTime(stats.lastVisit) : '—'}</Row>
                        <Row label="Favourite room">{stats.favouriteRoom || '—'}</Row>
                        <Row label="Most-booked movie">{stats.favouriteMovie || '—'}</Row>
                        <Row label="Abandoned checkouts">{stats.abandoned}</Row>
                    </div>

                    <div>
                        <p className="mb-2 text-xs font-medium uppercase tracking-wider text-zinc-500">Recent bookings</p>
                        {data.bookings.length === 0 ? <EmptyState icon={Ticket} title="No bookings yet" /> : (
                            <ul className="divide-y divide-zinc-800/80 rounded-lg border border-zinc-800">
                                {data.bookings.map(b => (
                                    <li key={b.id}>
                                        <button onClick={() => onOpenBooking(b.id)} className="flex w-full items-center gap-3 px-3 py-2.5 text-left hover:bg-zinc-900">
                                            <div className="min-w-0 flex-1">
                                                <p className="truncate text-sm text-zinc-100">{b.movie}</p>
                                                <p className="truncate text-xs text-zinc-500">
                                                    {b.showStart ? formatDateTime(b.showStart) : 'Show removed'}{b.theaterType ? ` · ${b.theaterType}` : ''} · {b.seats.length} seat{b.seats.length === 1 ? '' : 's'}
                                                </p>
                                            </div>
                                            <div className="text-right">
                                                <p className="text-sm tabular-nums text-zinc-100">{formatMoney(b.amount)}</p>
                                                <PaymentBadge isPaid={b.isPaid} />
                                            </div>
                                        </button>
                                    </li>
                                ))}
                            </ul>
                        )}
                    </div>
                </div>
            )}
        </Drawer>
    );
};

